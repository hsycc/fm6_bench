#!/usr/bin/env python3
"""Generate a 1025-entry Q15 quarter-wave sine table.

1024 intervals per quadrant give 4096 discrete phase positions per full cycle,
matching the phase resolution observed in the stock FM-1 operator lookup
(phase >> 12, quadrant fold, low 10-bit table index).
"""
import math
import sys
from pathlib import Path

if len(sys.argv) != 2:
    raise SystemExit("usage: gen_qsine4096.py OUTPUT_HEADER")

out = Path(sys.argv[1])
vals = []
for i in range(1025):
    # Keep the same signed Q15 peak convention as the Felucca benchmark table.
    v = int(round(math.sin((math.pi * 0.5 * i) / 1024.0) * 32767.0))
    vals.append(max(-32768, min(32767, v)))

lines = [
    "/* Generated by scripts/gen_qsine4096.py. */",
    "#ifndef BENCH_QSINE4096_H",
    "#define BENCH_QSINE4096_H",
    "#include <stdint.h>",
    "static const int16_t BENCH_QSINE4096[1025] = {",
]
for i in range(0, len(vals), 16):
    lines.append("    " + ", ".join(str(v) for v in vals[i:i+16]) + ",")
lines += ["};", "#endif", ""]
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text("\n".join(lines))
print(f"generated {out}: 1025 Q15 quarter-wave entries")
